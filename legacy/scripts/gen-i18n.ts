// Generates vendor/i18n.js for the classic game from the shared site catalog,
// so translations live in exactly one place (remaster/src/i18n/catalog.ts).
import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { CATALOG, LANGS, RTL_LANGS } from "../../remaster/src/i18n/catalog";

const legacyDir = resolve(import.meta.dir, "..");

const js = `// Generated by scripts/gen-i18n.ts — do not edit by hand.
window.BUBBLES_I18N = ${JSON.stringify({ langs: LANGS, rtl: RTL_LANGS, catalog: CATALOG })};
window.BI18N = (function () {
	var data = window.BUBBLES_I18N;
	var KEY = "bubbles.lang";
	function known(code) {
		for (var i = 0; i < data.langs.length; i++) if (data.langs[i].code === code) return true;
		return false;
	}
	// Same resolution as the remaster (remaster/src/i18n.ts): saved locale
	// (legacy base codes like "es" migrate to the first matching locale) →
	// navigator.language → first locale sharing its base language → langs[0].
	function resolve() {
		var saved = null;
		try { saved = localStorage.getItem(KEY); } catch (e) {}
		if (saved) {
			if (known(saved)) return saved;
			for (var i = 0; i < data.langs.length; i++) {
				if (data.langs[i].code.indexOf(saved) === 0) return data.langs[i].code;
			}
		}
		var nav = navigator.language || data.langs[0].code;
		if (known(nav)) return nav;
		var base = nav.slice(0, 2);
		for (var j = 0; j < data.langs.length; j++) {
			if (data.langs[j].code.indexOf(base) === 0) return data.langs[j].code;
		}
		return data.langs[0].code;
	}
	var api = { lang: resolve(), langs: data.langs };
	// Per-key: country variant ("pt-PT") → base language ("pt") → es for
	// es-* locales, en for everything else → the key itself.
	api.t = function (key) {
		var lang = api.lang;
		var base = lang.slice(0, 2);
		var last = base === "es" ? data.catalog.es : data.catalog.en;
		var variant = data.catalog[lang], baseCat = data.catalog[base];
		if (variant && variant[key] != null) return variant[key];
		if (baseCat && baseCat[key] != null) return baseCat[key];
		return last[key] != null ? last[key] : key;
	};
	api.fmt = function (key, vars) {
		return api.t(key).replace(/\\{(\\w+)\\}/g, function (m, k) {
			return vars && k in vars ? String(vars[k]) : m;
		});
	};
	api.isRtl = function () {
		return data.rtl.indexOf(api.lang.slice(0, 2)) !== -1;
	};
	// Switches language in place: later t()/fmt() calls use the new one.
	api.setLang = function (code) {
		api.lang = code;
		try { localStorage.setItem(KEY, code); } catch (e) {}
	};
	return api;
})();
`;

await mkdir(join(legacyDir, "vendor"), { recursive: true });
await Bun.write(join(legacyDir, "vendor", "i18n.js"), js);
console.log("vendor/i18n.js");
